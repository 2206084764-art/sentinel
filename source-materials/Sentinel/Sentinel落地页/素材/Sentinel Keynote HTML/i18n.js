/* ---- language runtime -------------------------------------------------
   Translation is a local dictionary lookup (SX_DICT above): nothing is sent
   anywhere and no service is called when the language changes.
   Originals are cached per node the first time we touch them, so switching
   from one language straight to another still resolves against English. */
(function () {
  var LANGS = [
    { c: "en", n: "English",    f: "EN" },
    { c: "es", n: "Español",    f: "ES" },
    { c: "pt", n: "Português",  f: "PT" },
    { c: "fr", n: "Français",   f: "FR" },
    { c: "it", n: "Italiano",   f: "IT" },
    { c: "ar", n: "العربية",     f: "AR" }
  ];
  var ATTRS = ["alt", "title", "aria-label", "placeholder"];
  var SKIP  = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, IFRAME: 1, CANVAS: 1 };

  var lang = "en";
  try { lang = localStorage.getItem("sx-lang") || "en"; } catch (e) {}
  if (!LANGS.some(function (l) { return l.c === lang; })) lang = "en";

  var origText = new WeakMap();   // text node -> English source
  var origAttr = new WeakMap();   // element  -> { attr: English source }

  function t(s) {
    if (!s) return s;
    if (lang === "en") return s;
    var d = window.SX_DICT && window.SX_DICT[lang];
    if (!d) return s;
    var k = String(s).trim();
    if (!k) return s;
    var hit = d[k];
    return hit === undefined ? s : String(s).replace(k, hit);
  }

  function walk(root) {
    var it = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        if (!n.nodeValue || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        var p = n.parentNode;
        if (!p || SKIP[p.nodeName]) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    var n, nodes = [];
    while ((n = it.nextNode())) nodes.push(n);
    nodes.forEach(function (node) {
      if (!origText.has(node)) origText.set(node, node.nodeValue);
      node.nodeValue = t(origText.get(node));
    });
    var els = root.querySelectorAll("[" + ATTRS.join("],[") + "]");
    Array.prototype.forEach.call(els, function (el) {
      var store = origAttr.get(el) || {};
      ATTRS.forEach(function (a) {
        var cur = el.getAttribute(a);
        if (cur === null) return;
        if (store[a] === undefined) store[a] = cur;
        el.setAttribute(a, t(store[a]));
      });
      origAttr.set(el, store);
    });
  }

  function apply() {
    var html = document.documentElement;
    html.setAttribute("lang", lang);
    html.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
    walk(document.body);
    document.querySelectorAll(".lang-opt").forEach(function (b) {
      b.classList.toggle("on", b.dataset.lang === lang);
    });
    var cur = document.getElementById("langCur");
    if (cur) cur.textContent = (LANGS.filter(function (l) { return l.c === lang; })[0] || LANGS[0]).f;
    document.dispatchEvent(new CustomEvent("sx-lang", { detail: { lang: lang } }));
  }

  function setLang(l) {
    lang = l;
    try { localStorage.setItem("sx-lang", l); } catch (e) {}
    apply();
  }

  function build() {
    var wrap = document.getElementById("langsw");
    if (wrap) { bind(wrap); return; }          // already in the HTML — just wire it
    var nav = document.querySelector("nav .wrap");
    if (!nav) return;
    wrap = document.createElement("div");
    wrap.className = "langsw";
    wrap.id = "langsw";
    wrap.innerHTML =
      '<button class="lang-btn" id="langBtn" aria-haspopup="true" aria-expanded="false" aria-label="Choose language">' +
        '<svg viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="9"/>' +
        '<path d="M3 12h18M12 3c2.6 2.7 2.6 15.3 0 18M12 3c-2.6 2.7-2.6 15.3 0 18"/></svg>' +
        '<span id="langCur">EN</span></button>' +
      '<div class="lang-menu" id="langMenu" role="menu">' +
        LANGS.map(function (l) {
          return '<button class="lang-opt" role="menuitem" data-lang="' + l.c + '" lang="' + l.c + '">' +
                 '<span class="lf">' + l.f + '</span>' + l.n + '</button>';
        }).join("") +
      "</div>";
    nav.appendChild(wrap);
    bind(wrap);
  }

  function bind(wrap) {
    if (wrap.dataset.bound) return;
    wrap.dataset.bound = "1";
    var btn = wrap.querySelector("#langBtn"), menu = wrap.querySelector("#langMenu");
    function close() { wrap.classList.remove("open"); btn.setAttribute("aria-expanded", "false"); }
    btn.addEventListener("click", function (e) {
      e.stopPropagation();
      var open = wrap.classList.toggle("open");
      btn.setAttribute("aria-expanded", open ? "true" : "false");
    });
    menu.addEventListener("click", function (e) {
      var b = e.target.closest(".lang-opt");
      if (!b) return;
      setLang(b.dataset.lang);
      close();
    });
    document.addEventListener("click", close);
    document.addEventListener("keydown", function (e) { if (e.key === "Escape") close(); });
  }

  window.I18N = { t: t, apply: apply, set: setLang, get lang() { return lang; } };

  function boot() { build(); apply(); }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot);
  else boot();
})();
